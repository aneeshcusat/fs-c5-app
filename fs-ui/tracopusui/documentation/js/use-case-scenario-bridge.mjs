export function scenariosForUseCase(useCaseId) {
  return Object.entries(SCENARIO_TO_USE_CASE)
    .filter(([, uc]) => uc === useCaseId)
    .map(([scenarioId]) => ({
      id: scenarioId,
      module: SCENARIO_MODULES[scenarioId] || "hrms",
      title: SCENARIO_TITLES[scenarioId] || scenarioId,
    }));
}

export function useCaseForScenario(scenarioId) {
  return SCENARIO_TO_USE_CASE[scenarioId] || null;
}
